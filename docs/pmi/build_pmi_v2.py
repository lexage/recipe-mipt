def _clean_rpr(rpr):
    if rpr is None:
        return None
    rpr = copy.deepcopy(rpr)
    for tag in ("w:highlight",):
        for el in rpr.findall(qn(tag)):
            rpr.remove(el)
    return rpr


def set_text(p, text, rpr=None):
    """Replace the paragraph's content with one run, keeping pPr and run format."""
    runs = p.findall(qn("w:r"))
    if rpr is None and runs:
        rpr = runs[0].find(qn("w:rPr"))
    rpr = _clean_rpr(rpr)
    for child in list(p):
        if child.tag != qn("w:pPr"):
            p.remove(child)
    r = OxmlElement("w:r")
    if rpr is not None:
        r.append(rpr)
    t = OxmlElement("w:t")
    t.set(qn("xml:space"), "preserve")
    t.text = text
    r.append(t)
    p.append(r)
    return p


def para(kind, text=""):
    p = copy.deepcopy(PROTO[kind])
    if kind == "blank":
        return p
    set_text(p, text)
    if kind == "cap":  # подпись таблицы — на одной странице с таблицей
        keep_next(p)
    return p


def _first_rpr(el):
    for r in el.iter(qn("w:r")):
        rpr = r.find(qn("w:rPr"))
        if rpr is not None:
            return rpr
    return None


def set_cell(tc, text, fallback_rpr):
    ps = tc.findall(qn("w:p"))
    first = ps[0]
    for extra in ps[1:]:
        tc.remove(extra)
    rpr = _first_rpr(first)
    if rpr is None:
        rpr = fallback_rpr
    lines = text.split("\n")
    set_text(first, lines[0], rpr)
    anchor = first
    for line in lines[1:]:
        p = copy.deepcopy(first)
        set_text(p, line, rpr)
        anchor.addnext(p)
        anchor = p


WIDTHS = {"t4": [1100, 5006, 2600, 1500], "t3": [800, 4700, 4706], "t2": [7206, 3000]}


def keep_next(p):
    ppr = p.find(qn("w:pPr"))
    if ppr is None:
        ppr = OxmlElement("w:pPr")
        p.insert(0, ppr)
    if ppr.find(qn("w:keepNext")) is None:
        k = OxmlElement("w:keepNext")
        first = ppr[0] if len(ppr) else None
        # порядок по схеме: pStyle, затем keepNext
        ppr.insert(1 if first is not None and first.tag == qn("w:pStyle") else 0, k)


def set_widths(t, widths):
    grid = t.find(qn("w:tblGrid"))
    for col, w in zip(grid.findall(qn("w:gridCol")), widths):
        col.set(qn("w:w"), str(w))
    for tr in t.findall(qn("w:tr")):
        for tc, w in zip(tr.findall(qn("w:tc")), widths):
            tcw = tc.find(qn("w:tcPr")).find(qn("w:tcW"))
            tcw.set(qn("w:w"), str(w))
            tcw.set(qn("w:type"), "dxa")


def table(kind, header, rows):
    t = copy.deepcopy(TPROTO[kind])
    trs = t.findall(qn("w:tr"))
    head, tmpl = trs[0], copy.deepcopy(trs[1])
    fallback = _first_rpr(t)
    for tr in trs[1:]:
        t.remove(tr)
    if header:
        for tc, value in zip(head.findall(qn("w:tc")), header):
            set_cell(tc, value, fallback)
    for p in head.iter(qn("w:p")):  # шапка не отрывается от первой строки
        keep_next(p)
    for row in rows:
        tr = copy.deepcopy(tmpl)
        tcs = tr.findall(qn("w:tc"))
        assert len(tcs) == len(row), (kind, row)
        for tc, value in zip(tcs, row):
            set_cell(tc, value, fallback)
        t.append(tr)
    set_widths(t, WIDTHS[kind])
    return t


